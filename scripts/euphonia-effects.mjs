// What the rules the builder reads from the books come to, recorded so a rule
// that stops being read can't vanish quietly. The engine reads the books'
// sentences: reword one it knows and its effect goes, with nothing to say so.
// Each class and subclass (and each model it offers), each of the setting's
// backgrounds and each magic item is built; its effects are held in
// euphonia-effects.json, which verify-euphonia-builder compares with what the
// engine makes now. After a release that changes a rule on purpose, check what
// the gate lists, then run this to record it. Never part of the build:
//   node scripts/euphonia-effects.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import * as defaultEngine from '../src/euphonia/euphonia.character.js';

const LEDGER = new URL('./euphonia-effects.json', import.meta.url);
const SCORES = { Strength: 15, Dexterity: 14, Constitution: 13, Intelligence: 13, Wisdom: 13, Charisma: 13 };
const MAX = 20, ITEM_LEVEL = 11;
const someone = (classes, extra = {}) => ({ species: 'Human', size: 'Medium', background: 'Soldier', increases: { Strength: 1, Dexterity: 1, Constitution: 1 }, method: 'rolled', base: SCORES, classes, ...extra });

// A built character's rules' effects, one line each.
function linesOf(r) {
  const list = (label, xs) => xs.map(x => `${label}: ${x}`);
  return [
    `Armor Class: ${r.armorClass.ac} (${r.armorClass.from})`, `Hit Points: ${r.hp}`, `Speed: ${r.speed}`, `Initiative: ${r.initiative}`, `Passive Perception: ${r.passivePerception}`, `Attacks per action: ${r.attacksPerAction}`,
    ...list('Speed', Object.entries(r.speeds).map(([k, v]) => `${k} ${v}`)), ...list('Sense', Object.entries(r.senses).map(([k, v]) => `${k} ${v}`)),
    ...Object.entries(r.defenses).flatMap(([k, v]) => list(k, v)), ...list('Hit Points from', r.hpFrom.map(x => `${x.hp} ${x.from}`)),
    ...list('Without armor', r.unarmored.map(u => `${u.ac} ${u.from}`)), ...list('Armor training', r.training),
    ...list('Weapons', [...r.weaponTraining.categories, ...r.weaponTraining.named]), ...list('Save', r.saves.map(s => `${s.ability} ${s.bonus}`)),
    ...list('Attack', r.attacks.map(a => [a.name, a.save ? `DC ${a.save.dc} ${a.save.ability}` : a.bonus, a.damage, a.versatile, a.reach, ...a.riders].filter(x => x !== null && x !== undefined).join(' | '))),
    ...list('Reads', r.read),
  ].map(String).sort();
}

export function effectsOf(engine, book) {
  const out = {}, build = state => linesOf(engine.character(book, state));
  const without = (lines, base) => { const had = new Set(base); return lines.filter(l => !had.has(l)); };
  for (const c of book.classes) for (const subclass of [undefined, ...c.subclasses.map(s => s.name)]) {
    const state = someone([{ class: c.name, level: MAX, subclass }]), key = `${c.name}${subclass ? `, ${subclass}` : ''}`;
    out[key] = build(state);
    const made = engine.character(book, state);
    for (const k of made.kindChoices) for (const offered of k.offered) out[`${key}, ${offered}`] = without(build({ ...state, kinds: { [k.key]: offered } }), out[key]);
    // Picks offered from sets (the Attunements), each set taken at every level.
    const picks = made.swapChoices.filter(p => p.from);
    for (const set of new Set(picks.flatMap(p => Object.values(p.from)))) out[`${key}, ${set} set`] = without(build({ ...state, swaps: Object.fromEntries(picks.map(p => [p.key, Object.keys(p.from).find(n => p.from[n] === set)])) }), out[key]);
  }
  const plain = someone([{ class: 'Fighter', level: ITEM_LEVEL }]), base = build(plain);
  for (const b of book.backgrounds.filter(x => x.source === 'Euphonia')) out[`Background: ${b.name}`] = without(build({ ...plain, background: b.name }), base);
  for (const i of book.items.filter(x => x.magical)) for (const { rarity } of i.rarities) out[`Item: ${i.name}, ${rarity}`] = without(build({ ...plain, inventory: { add: [{ name: i.name, rarity, how: 'given' }] } }), base);
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : 1)));
}

export const recorded = () => JSON.parse(readFileSync(LEDGER, 'utf8')).builds;

// What differs: each effect lost or new, by build.
export function differences(was, now) {
  const out = [];
  for (const key of new Set([...Object.keys(was), ...Object.keys(now)])) {
    const a = new Set(was[key] ?? []), b = new Set(now[key] ?? []);
    for (const l of a) if (!b.has(l)) out.push(`${key}: lost "${l}"`);
    for (const l of b) if (!a.has(l)) out.push(`${key}: new "${l}"`);
  }
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const read = n => JSON.parse(readFileSync(new URL(`../src/euphonia/euphonia.${n}.json`, import.meta.url), 'utf8'));
  const builds = effectsOf(defaultEngine, defaultEngine.rulebook(read('srd'), read('classes'), read('characters'), read('subclasses'), read('items').data));
  writeFileSync(LEDGER, `${JSON.stringify({ about: 'Generated by euphonia-effects.mjs: what each rule the builder reads comes to. Never edited by hand.', builds }, null, 0)}\n`);
  console.log(`euphonia-effects.json: ${Object.keys(builds).length} builds, ${Object.values(builds).flat().length} effects`);
}
